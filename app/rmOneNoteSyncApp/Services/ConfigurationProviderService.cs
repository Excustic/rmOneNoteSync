using System;
using System.Collections.Generic;
using System.Net.Http;
using System.Text;
using System.Text.Json;
using System.Threading.Tasks;
using Microsoft.Extensions.Logging;
using rmOneNoteSyncApp.Models;
using rmOneNoteSyncApp.Services.Interfaces;

namespace rmOneNoteSyncApp.Services;

public class ConfigurationProviderService(
    ILogger<ConfigurationProviderService> logger,
    IDatabaseService databaseService,
    ISshService sshService,
    IDeviceDetectionService deviceDetectionService)
    : IConfigurationProviderService
{
    private const string RemarkableIp = AppSettings.DefaultDeviceIp;
    public const string ConfigPath = "/home/root/onenote-sync/daemon.conf";
    private static readonly JsonSerializerOptions _jsonOptions = new() { WriteIndented = true, PropertyNamingPolicy = JsonNamingPolicy.CamelCase };

    string IConfigurationProviderService.ConfigPath => ConfigPath;

    public async Task<bool> UpdateDeviceConfigurationAsync(bool restartService = true)
    {
        try
        {
            var success = true;
            success &= await RegisterEndpointAsync();
            success &= await UpdateWhitelistAsync();
            success &= await UpdateDaemonSettingsAsync(restartService);
            return success;
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Failed to update reMarkable configuration");
            return false;
        }
    }

    public async Task<bool> UpdateDaemonSettingsAsync(bool restartService = true)
    {
        try
        {
            var config = await databaseService.GetConfigurationAsync();
            var deviceIp = deviceDetectionService.CurrentDevice?.IpAddress ?? RemarkableIp;
            var configUrl = $"http://{deviceIp}:8000/config";

            var configBuilder = new StringBuilder();
            configBuilder.AppendLine("# Auto-generated by rmOneNoteSyncApp");
            configBuilder.AppendLine($"# Generated at: {DateTime.Now:yyyy-MM-dd HH:mm:ss}");
            configBuilder.AppendLine();
            configBuilder.AppendLine("API_KEY=rmOneNoteSync");
            configBuilder.AppendLine($"UPLOAD_INTERVAL={config?.SyncIntervalSeconds ?? 300}");
            configBuilder.AppendLine($"MAX_RETRIES={config?.MaxRetries ?? 3}");
            configBuilder.AppendLine($"RETRY_DELAY={config?.RetryDelaySeconds ?? 5}");
            configBuilder.AppendLine($"TIMEOUT={config?.TimeoutSeconds ?? 10}");
            configBuilder.AppendLine($"AUTO_ADD_NEW_FILES={(config?.AutoAddNewFiles == true ? "1" : "0")}");

            using var httpClient = new HttpClient { Timeout = TimeSpan.FromSeconds(10) };
            var content = new StringContent(configBuilder.ToString(), Encoding.UTF8, "text/plain");
            var response = await httpClient.PostAsync(configUrl, content);

            if (!response.IsSuccessStatusCode)
            {
                logger.LogWarning("HTTP config POST failed ({Status}).", response.StatusCode);
                return false;
            }

            if (restartService && sshService.IsConnected)
            {
                logger.LogDebug("Restarting httpclient service");
                await sshService.ExecuteCommandAsync("systemctl restart onenote-sync-httpclient");
            }

            return true;
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Failed to update daemon settings");
            return false;
        }
    }

    public async Task<bool> RegisterEndpointAsync()
    {
        try
        {
            var config = await databaseService.GetConfigurationAsync();
            int serverPort = config?.SyncServerPort ?? AppSettings.DefaultServerPort;
            var deviceIp = deviceDetectionService.CurrentDevice?.IpAddress ?? RemarkableIp;

            // Resolve host IPs
            // 1. USB Interface (Always try to resolve host IP relative to 10.11.99.1)
            var usbHostIp = await deviceDetectionService.GetLocalIpAddressForDevice(RemarkableIp);
            
            // 2. WiFi Interface (Try to resolve host IP relative to the current or last known device WiFi IP)
            string? wifiDeviceIp = (deviceDetectionService.CurrentDevice?.ConnectionType == DeviceConnectionType.WiFi)
                ? deviceDetectionService.CurrentDevice.IpAddress
                : config?.LastNetworkIp;
                
            var wifiHostIp = !string.IsNullOrEmpty(wifiDeviceIp) 
                ? await deviceDetectionService.GetLocalIpAddressForDevice(wifiDeviceIp)
                : null;

            using var httpClient = new HttpClient { Timeout = TimeSpan.FromSeconds(3) };
            
            // We need to reach the device to register our endpoints.
            // Try all possible device IPs (USB and WiFi) as destinations for our registration request.
            var deviceIpCandidates = new HashSet<string> { RemarkableIp };
            if (!string.IsNullOrEmpty(wifiDeviceIp))
            {
                deviceIpCandidates.Add(wifiDeviceIp);
            }

            foreach (var devIp in deviceIpCandidates)
            {
                var endpointUrl = $"http://{devIp}:8000/endpoints/add";
                
                // Try registering USB endpoint on this device IP
                if (!string.IsNullOrEmpty(usbHostIp))
                {
                    await TryRegisterAsync(httpClient, endpointUrl, usbHostIp, serverPort, "USB");
                }

                // Try registering WiFi endpoint on this device IP
                if (!string.IsNullOrEmpty(wifiHostIp) && wifiHostIp != usbHostIp)
                {
                    await TryRegisterAsync(httpClient, endpointUrl, wifiHostIp, serverPort, "WiFi");
                }
            }

            return true;
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Critical error in RegisterEndpointAsync");
            return false;
        }
    }

    private async Task TryRegisterAsync(HttpClient client, string targetUrl, string hostIp, int port, string label)
    {
        try
        {
            var endpoint = $"http://{hostIp}:{port}";
            logger.LogDebug("Attempting to register {Label} endpoint {Url} via {Target}", label, endpoint, targetUrl);
            
            var payload = JsonSerializer.Serialize(new { url = endpoint });
            var content = new StringContent(payload, Encoding.UTF8, "application/json");
            
            var response = await client.PostAsync(targetUrl, content);
            if (response.IsSuccessStatusCode)
            {
                logger.LogInformation("Successfully registered {Label} endpoint via {Target}", label, targetUrl);
            }
            else
            {
                logger.LogWarning("Failed to register {Label} endpoint via {Target}. Status: {Status}", label, targetUrl, response.StatusCode);
            }
        }
        catch (TaskCanceledException)
        {
            logger.LogDebug("Timeout registering {Label} endpoint via {Target} (Interface likely disconnected)", label, targetUrl);
        }
        catch (Exception ex)
        {
            logger.LogWarning("Error registering {Label} endpoint via {Target}: {Message}", label, targetUrl, ex.Message);
        }
    }

    public async Task<bool> UpdateWhitelistAsync()
    {
        try
        {
            var config = await databaseService.GetConfigurationAsync();
            var deviceIp = deviceDetectionService.CurrentDevice?.IpAddress ?? RemarkableIp;
            var whitelistUrl = $"http://{deviceIp}:8000/whitelist";

            var payload = new
            {
                whitelist = config?.SyncFiles ?? [],
                sync_folders = config?.SyncFolders ?? []
            };

            using var httpClient = new HttpClient { Timeout = TimeSpan.FromSeconds(10) };
            var content = new StringContent(JsonSerializer.Serialize(payload), Encoding.UTF8, "application/json");
            var response = await httpClient.PutAsync(whitelistUrl, content);

            return response.IsSuccessStatusCode;
        }
        catch (Exception ex)
        {
            logger.LogError(ex, "Failed to update whitelist");
            return false;
        }
    }

    public async Task<(List<string> Whitelist, List<string> SyncFolders)> FetchWhitelistFromDeviceAsync()
    {
        try
        {
            var deviceIp = deviceDetectionService.CurrentDevice?.IpAddress ?? RemarkableIp;
            var whitelistUrl = $"http://{deviceIp}:8000/whitelist";

            using var httpClient = new HttpClient { Timeout = TimeSpan.FromSeconds(5) };
            var response = await httpClient.GetAsync(whitelistUrl);

            if (response.IsSuccessStatusCode)
            {
                var content = await response.Content.ReadAsStringAsync();
                var options = new JsonSerializerOptions { PropertyNameCaseInsensitive = true };
                var result = JsonSerializer.Deserialize<WhitelistResponse>(content, options);
                
                return (result?.Whitelist ?? [], result?.SyncFolders ?? []);
            }
        }
        catch (Exception ex)
        {
            logger.LogWarning("Failed to fetch whitelist from device: {Message}", ex.Message);
        }

        return ([], []);
    }

    private class WhitelistResponse
    {
        public List<string> Whitelist { get; set; } = [];
        public List<string> SyncFolders { get; set; } = [];
    }

    public async Task<int> GetServerPortAsync()
    {
        var config = await databaseService.GetConfigurationAsync();
        return config?.SyncServerPort ?? AppSettings.DefaultServerPort;
    }
}